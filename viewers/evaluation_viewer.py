class EvaluationStore:
    def __init__(self, root: Path, manifest: Optional[dict], max_preview_chars: int):
        self.root = root
        self.max_preview_chars = max_preview_chars
        self.manifest = manifest or {}
        self.datasets: Dict[str, hfds.Dataset] = {}
        self.descriptions: Dict[str, str] = {}
        self._load_datasets()

    def _load_datasets(self):
        manifest_tasks = {item.get("task"): item for item in self.manifest.get("tasks", [])}
        for entry in sorted(self.root.iterdir()):
            if not entry.is_dir():
                continue
            name = entry.name
            try:
                ds = hfds.load_from_disk(str(entry))
            except Exception as exc:
                print(f"⚠️  Failed to load dataset '{name}': {exc}", flush=True)
                continue
            if len(ds) == 0:
                continue
            self.datasets[name] = ds
            self.descriptions[name] = manifest_tasks.get(name, {}).get("description", "")

    def list_tasks(self) -> List[dict]:
        items = []
        for name, ds in self.datasets.items():
            items.append({
                "name": name,
                "count": len(ds),
                "description": self.descriptions.get(name, ""),
            })
        return items

    def list_examples(self, task: str, offset: int, limit: int) -> List[dict]:
        ds = self.datasets.get(task)
        if ds is None:
            raise KeyError(task)
        offset = max(0, offset)
        limit = max(1, min(limit, 100))
        hi = min(len(ds), offset + limit)
        examples = []
        for idx in range(offset, hi):
            example = ds[idx]
            snippet = example["content"][:200].replace("\n", " ").strip()
            examples.append({
                "index": idx,
                "example_id": example.get("example_id", ""),
                "task": example.get("task", task),
                "snippet": snippet,
                "source_langs": example.get("source_langs", []),
            })
        return examples

    def get_example(self, task: str, index: int) -> Tuple[dict, int]:
        ds = self.datasets.get(task)
        if ds is None:
            raise KeyError(task)
        if index < 0 or index >= len(ds):
            raise IndexError(index)
        return ds[index], len(ds)


