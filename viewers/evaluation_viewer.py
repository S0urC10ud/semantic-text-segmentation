def _resolve_backend(device_name: Optional[str]) -> Optional[str]:
    if not device_name or device_name.lower() in {"auto", "default"}:
        return None
    lower = device_name.lower()
    if lower == "cuda":
        lower = "gpu"
    if lower not in {"cpu", "gpu", "tpu"}:
        raise ValueError(f"Unknown device '{device_name}'. Use cpu/gpu/cuda/auto.")
    # If GPU is requested but not available, fall back to CPU
    if lower == "gpu" and not any(dev.platform == "gpu" for dev in jax.devices()):
        print("⚠️  GPU requested but not available, falling back to CPU", flush=True)
        return "cpu"
    return lower


def _window_weights(length: int) -> np.ndarray:
    if length <= 1:
        return np.ones((length,), dtype=np.float32)
    positions = np.linspace(-1.0, 1.0, num=length, dtype=np.float32)
    sigma = 0.5
    weights = np.exp(-0.5 * (positions / sigma) ** 2)
    return weights.astype(np.float32)


def _segments_to_labels(length: int, segments: Sequence[dict], unknown: str) -> List[str]:
    labels = [unknown] * length
    for seg in segments:
        label = seg.get("label", unknown)
        start = max(0, min(length, int(seg.get("char_start", 0))))
        end = max(start, min(length, int(seg.get("char_end", 0))))
        if end <= start:
            continue
        labels[start:end] = [label] * (end - start)
    return labels


def _trim_content(content: str, segments: Sequence[dict], max_chars: int) -> Tuple[str, List[dict], bool]:
    if max_chars <= 0 or len(content) <= max_chars:
        return content, list(segments), False
    trimmed = content[:max_chars]
    adjusted: List[dict] = []
    for seg in segments:
        start = seg.get("char_start", 0)
        end = seg.get("char_end", 0)
        if end <= 0 or start >= max_chars:
            continue
        adj = {
            "label": seg.get("label"),
            "char_start": max(0, min(max_chars, int(start))),
            "char_end": max(0, min(max_chars, int(end))),
        }
        if adj["char_end"] > adj["char_start"]:
            adjusted.append(adj)
    return trimmed, adjusted, True


def _compress_pairs(truth: Sequence[str], pred: Sequence[str]) -> List[dict]:
    length = min(len(truth), len(pred))
    spans: List[dict] = []
    if length == 0:
        return spans
    start = 0
    cur_truth = truth[0]
    cur_pred = pred[0]
    for idx in range(1, length):
        if truth[idx] != cur_truth or pred[idx] != cur_pred:
            spans.append({
                "start": start,
                "end": idx,
                "truth": cur_truth,
                "pred": cur_pred,
                "match": cur_truth == cur_pred,
            })
            start = idx
            cur_truth = truth[idx]
            cur_pred = pred[idx]
    spans.append({
        "start": start,
        "end": length,
        "truth": cur_truth,
        "pred": cur_pred,
        "match": cur_truth == cur_pred,
    })
    return spans


