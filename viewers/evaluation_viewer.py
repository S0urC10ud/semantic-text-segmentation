@app.get("/api/sample")
def api_sample(task: str, index: int):
    try:
        example, total = store.get_example(task, index)
    except KeyError:
        raise HTTPException(status_code=404, detail=f"Unknown task '{task}'")
    except IndexError:
        raise HTTPException(status_code=404, detail=f"Index {index} out of range for task '{task}'")

    content = example["content"]
    truth_segments = _normalize_segments(example.get("segments", []))
    content_view, truth_segments_view, truncated = _trim_content(content, truth_segments, store.max_preview_chars)
    unknown_label = "__unknown__"
    truth_labels = _segments_to_labels(len(content_view), truth_segments_view, unknown_label)

    if runner is not None:
        pred_char_ids, _, raw_char_probs = runner.segment_text(content_view, min_run_chars=max(1, args.min_run))
        pred_labels: List[str] = []
        for cid in pred_char_ids:
            pred_labels.append(
                _prediction_label_from_id(
                    int(cid),
                    num_classes=int(runner.num_classes),
                    unknown_label=unknown_label,
                )
            )
    else:
        raw_char_probs = []
        pred_labels = [unknown_label] * len(content_view)

    label_order: List[str] = []
    char_data: List[dict] = []
    char_count = len(content_view)
    for idx in range(char_count):
        ch = content_view[idx]
        truth_lbl = truth_labels[idx] if idx < len(truth_labels) else unknown_label
        pred_lbl = pred_labels[idx] if idx < len(pred_labels) else unknown_label
        match = truth_lbl == pred_lbl

        if truth_lbl and truth_lbl not in label_order and truth_lbl != unknown_label:
            label_order.append(truth_lbl)
        if pred_lbl and pred_lbl not in label_order and pred_lbl != unknown_label:
            label_order.append(pred_lbl)

        probs_entries: List[dict] = []
        if idx < len(raw_char_probs):
            agg: Dict[str, float] = {}
            vector = raw_char_probs[idx]
            for class_idx, prob in enumerate(vector):
                prob_value = float(prob)
                if prob_value <= 0.0:
                    continue
                label_name = cfg.ID2LANG.get(int(class_idx))
                if not label_name:
                    continue
                label_name = PREDICTION_LABEL_ALIASES.get(label_name, label_name)
                agg[label_name] = agg.get(label_name, 0.0) + prob_value
            sorted_items = sorted(agg.items(), key=lambda kv: kv[1], reverse=True)
            cutoff = 10
            total_appended = 0.0
            for pos, (lbl, prob) in enumerate(sorted_items):
                if pos < cutoff:
                    probs_entries.append({"label": lbl, "prob": float(prob)})
                    total_appended += prob
                else:
                    break
            remainder = sum(prob for _, prob in sorted_items[cutoff:])
            if remainder > 1e-6:
                probs_entries.append({"label": "others", "prob": float(remainder)})

        char_data.append({
            "char": ch,
            "truth": truth_lbl,
            "pred": pred_lbl,
            "match": bool(match),
            "probs": probs_entries,
        })

    spans = _compress_pairs(truth_labels, pred_labels)
    eval_total = 0
    eval_correct = 0
    for idx, (t, p) in enumerate(zip(truth_labels, pred_labels)):
        ch = content_view[idx] if idx < len(content_view) else ""
        if ch in _VISUAL_WHITESPACE_SET:
            continue
        if t == unknown_label:
            continue
        eval_total += 1
        if t == p:
            eval_correct += 1
    accuracy = float(eval_correct / eval_total) if eval_total else 0.0

    unique_labels = [lbl for lbl in label_order if lbl and lbl != unknown_label]
    palette = _build_sample_palette(unique_labels)
    label_colors = palette if palette else {"__unknown__": "#b2bec3"}
    label_order_payload = list(unique_labels)
    if "__unknown__" in label_colors and "__unknown__" not in label_order_payload:
        label_order_payload.append("__unknown__")

    response = {
        "task": task,
        "index": index,
        "total": total,
        "example_id": example.get("example_id", ""),
        "display_text": content_view,
        "truncated": truncated,
        "metadata_json": example.get("metadata_json"),
        "source_langs": example.get("source_langs", []),
        "metrics": {
            "evaluated_chars": eval_total,
            "correct_chars": eval_correct,
            "char_accuracy": accuracy if runner is not None else None,
            "preview_chars": len(content_view),
        },
        "dataset_only": runner is None,
        "prediction_config": {
            "other_threshold": None if runner is None else float(args.other_threshold or 0.0),
            "other_label": None if runner is None else "other",
        },
        "comparison_spans": spans,
        "label_colors": label_colors,
        "label_order": label_order_payload,
        "truth_segments": truth_segments_view,
        "char_data": char_data,
    }
    return response


