def _auto_color(label: str) -> str:
    base = sum(ord(c) for c in label) + len(label) * 97
    rng = random.Random(base)
    hue = rng.random()
    sat = 0.55
    lig = 0.55
    r, g, b = colorsys.hls_to_rgb(hue, lig, sat)
    return "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))


def _color_for(label: str) -> str:
    label = (label or "").lower()
    if label in DEFAULT_COLOR_BY_LABEL:
        return DEFAULT_COLOR_BY_LABEL[label]
    return _auto_color(label)


def _build_sample_palette(labels: Sequence[str], include_unknown: bool = True) -> Dict[str, str]:
    ordered: List[str] = []
    seen = set()
    for label in labels:
        if not label or label == "__unknown__":
            continue
        if label not in seen:
            seen.add(label)
            ordered.append(label)

    palette: Dict[str, str] = {}
    count = len(ordered)
    if count == 0:
        if include_unknown:
            palette["__unknown__"] = "#b2bec3"
        return palette

    for idx, label in enumerate(ordered):
        hue = (idx / count) % 1.0
        # Alternate lightness to keep adjacent hues distinct for large palettes
        lig = 0.45 + 0.12 * ((idx % 3) / 2.0)
        sat = 0.65
        r, g, b = colorsys.hls_to_rgb(hue, lig, sat)
        palette[label] = "#{:02x}{:02x}{:02x}".format(int(r * 255), int(g * 255), int(b * 255))

    if include_unknown:
        palette["__unknown__"] = "#b2bec3"
    return palette


def _normalize_segments(segments) -> List[Dict[str, int]]:
    if segments is None:
        return []
    if isinstance(segments, dict):
        def _ensure_list(value, size_hint: int, default=0):
            if value is None:
                return [default] * size_hint
            if isinstance(value, (str, bytes)):
                return [value] * (size_hint or 1)
            if isinstance(value, np.ndarray):
                return value.tolist()
            if isinstance(value, (list, tuple)):
                return list(value)
            try:
                return list(value)
            except TypeError:
                return [value] * size_hint if size_hint else [value]

        raw_labels = segments.get("label") or segments.get("labels") or []
        labels = _ensure_list(raw_labels, 0)
        starts = _ensure_list(segments.get("char_start") or segments.get("start"), len(labels))
        ends = _ensure_list(segments.get("char_end") or segments.get("end"), len(labels))
        normalized: List[Dict[str, int]] = []
        for label, start, end in zip(labels, starts, ends):
            if label is None:
                continue
            try:
                start_i = int(start)
                end_i = int(end)
            except (TypeError, ValueError):
                continue
            normalized.append({"label": str(label), "char_start": start_i, "char_end": end_i})
        return normalized
    if isinstance(segments, (list, tuple)):
        normalized = []
        for seg in segments:
            if not isinstance(seg, dict):
                continue
            label = seg.get("label")
            if label is None:
                continue
            try:
                start_i = int(seg.get("char_start", 0))
                end_i = int(seg.get("char_end", start_i))
            except (TypeError, ValueError):
                continue
            normalized.append({"label": str(label), "char_start": start_i, "char_end": end_i})
        return normalized
    raise TypeError(f"Unsupported segments type: {type(segments)}")


def _extract_run_id_from_checkpoint(path: Path) -> Optional[str]:
    name = path.name.lower()
    match = re.search(r"([a-z0-9]{8})", name)
    if not match:
        return None
    return match.group(1)


def _load_checkpoint_hparams(ckpt_path: Path) -> Dict[str, object]:
    run_id = _extract_run_id_from_checkpoint(ckpt_path)
    if not run_id:
        return {}
    wandb_root = REPO_ROOT / "train" / "wandb"
    if not wandb_root.exists():
        return {}
    try:
        import yaml  # type: ignore
    except Exception:
        return {}
    pattern = f"run-*-{run_id}"
    for run_dir in wandb_root.glob(pattern):
        config_path = run_dir / "files" / "config.yaml"
        if not config_path.exists():
            continue
        try:
            config_data = yaml.safe_load(config_path.read_text())
        except Exception:
            config_data = None
        if not isinstance(config_data, dict):
            config_data = {}
        result: Dict[str, object] = {}
        channels_val = config_data.get("channels", {}).get("value")
        if isinstance(channels_val, (list, tuple)):
            try:
                result["channels"] = [int(x) for x in channels_val]
            except (TypeError, ValueError):
                pass
        model_dim_val = config_data.get("model_dim", {}).get("value")
        if isinstance(model_dim_val, (int, float)):
            result["model_dim"] = int(model_dim_val)
        dtype_val = config_data.get("dtype", {}).get("value")
        if isinstance(dtype_val, str):
            result["dtype"] = dtype_val.rsplit(".", 1)[-1]

        summary_path = run_dir / "files" / "wandb-summary.json"
        if summary_path.exists():
            try:
                summary_data = json.loads(summary_path.read_text())
            except Exception:
                summary_data = None
            if isinstance(summary_data, dict):
                label_names: Dict[int, str] = {}
                prefix = "val/per_class/"
                for key in summary_data.keys():
                    if not key.startswith(prefix):
                        continue
                    remainder = key[len(prefix):]
                    head = remainder.split("/", 1)[0]
                    if "_" not in head:
                        continue
                    idx_str, label = head.split("_", 1)
                    try:
                        idx = int(idx_str)
                    except ValueError:
                        continue
                    label_names[idx] = label
                if label_names:
                    ordered = [label_names[i] for i in sorted(label_names)]
                    result["label_names"] = ordered
        if result:
            return result
    return {}


